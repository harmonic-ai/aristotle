    _write(tmp_path / "i1" / "b.vh")
    _write(tmp_path / "i2" / "b.vh")
    _write(tmp_path / "i2" / "c.vh")
    f = _write(tmp_path / "aristotle.f", "-I i1\n-I i2\nrtl/top.v\n")
