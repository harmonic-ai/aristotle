def _write(path: Path, text: str = "") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode())
    return path


def _read(path: Path, root: Path, environ: dict[str, str] | None = None) -> bundle.Bundle:
    return bundle.read(path, root, environ=environ or {})


def _archives(result: bundle.Bundle) -> list[str]:
    return [m.archive for m in result.members]


def test_a_file_in_the_servers_subset_goes_up_unchanged(tmp_path: Path):
    """A committed aristotle.f in the server's options, with every path inside, isn't regenerated."""
    _write(tmp_path / "rtl" / "top.sv", '`include "defs.svh"\nmodule top; endmodule\n')
    _write(tmp_path / "rtl" / "defs.svh")
    f = _write(tmp_path / "aristotle.f", "# block\n--top top\n-I rtl\n-D W=8\n--single-unit\nrtl/top.sv\n")
    result = _read(f, tmp_path)
    assert result.filelist_text is None
    assert _archives(result) == ["rtl/top.sv", "rtl/defs.svh"]
    assert [m.reason for m in result.members] == [f"named at {f}:6", f"included at {tmp_path / 'rtl' / 'top.sv'}:1"]


def test_simulator_syntax_is_generated_into_the_servers_options(tmp_path: Path):
    """+incdir+, +define+, -v, +libext+ and joined forms become the server's one-option-per-line file."""
    _write(tmp_path / "rtl" / "top.sv", '`include "defs.svh"\n')
    _write(tmp_path / "inc" / "defs.svh")
    _write(tmp_path / "lib" / "cells.v")
    (tmp_path / "unused").mkdir()
    f = _write(
        tmp_path / "aristotle.f",
        "+incdir+inc+unused\n+define+W=8+FAST\n-UOLD\n-GDEPTH=4\n-timescale=1ns/1ps\n-sv\n--top top\n"
        "-v lib/cells.v\n+libext+.v\nrtl/top.sv\n",
    )
    result = _read(f, tmp_path)
    assert result.filelist_text == (
        "# Generated by the aristotle CLI from aristotle.f, in the options Aristotle reads.\n"
        "--top top\n"
        "--single-unit\n"
        "--timescale 1ns/1ps\n"
        "-D W=8\n"
        "-D FAST\n"
        "-U OLD\n"
        "-G DEPTH=4\n"
        "-I inc\n"
        "-Y .v\n"
        "lib/cells.v\n"
        "rtl/top.sv\n"
    )
    assert _archives(result) == ["lib/cells.v", "rtl/top.sv", "inc/defs.svh"]


