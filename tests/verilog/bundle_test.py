def test_includes_in_comments_and_strings_are_not_followed(tmp_path: Path):
    """Only directives in code count; a macro, a system include and a missing file are listed as unresolved."""
    text = (
        '// `include "a.vh"\n/* `include "b.vh"\n*/ $display("`include \\"c.vh\\"");\n'
        '`include `HEADER\n`include <sys.vh>\n`include "missing.vh"\n'
    )
    _write(tmp_path / "top.v", text)
    for name in ("a.vh", "b.vh", "c.vh", "sys.vh"):
        _write(tmp_path / name)
    f = _write(tmp_path / "aristotle.f", "top.v\n")
    result = _read(f, tmp_path)
    assert _archives(result) == ["top.v"]
    assert [(i.line, i.name, i.form) for i in result.unresolved] == [
        (4, "`HEADER", "macro"),
        (5, "sys.vh", "system"),
        (6, "missing.vh", "quoted"),
    ]


