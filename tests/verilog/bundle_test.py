def _git_dir(folder: Path) -> Path:
    """A git directory by what it holds, under ``folder``'s own name, with a token in its config."""
    _write(folder / "HEAD", "ref: refs/heads/main\n")
    (folder / "objects").mkdir()
    (folder / "refs").mkdir()
    _write(folder / "config", "[remote]\n  url = https://placeholder-token@example.com/x\n")
    _write(folder / "hooks" / "inc.vh")
    return folder


