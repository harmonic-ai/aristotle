def test_includes_resolve_as_slang_searches(tmp_path: Path):
    """The includer's folder first, then each -I folder in order; nested includes are followed."""
    _write(tmp_path / "rtl" / "top.v", '`include "a.vh"\n`include "b.vh"\n')
    _write(tmp_path / "rtl" / "a.vh", '`include "c.vh"\n')
