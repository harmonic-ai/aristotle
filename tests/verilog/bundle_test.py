    assert _archives(result) == ["rtl/top.v", "rtl/a.vh", "i1/b.vh", "i2/c.vh"]
    assert [(i.line, i.name, i.target) for i in result.includes] == [
        (1, "a.vh", tmp_path / "rtl" / "a.vh"),
        (2, "b.vh", tmp_path / "i1" / "b.vh"),
        (1, "c.vh", tmp_path / "i2" / "c.vh"),
    ]


