def test_scan_includes_finds_what_it_did_before_it_skipped_system_includes_never_closed(
    monkeypatch: pytest.MonkeyPatch,
):
    rng = random.Random(3383)
    pieces = ["`include", "`include <", '`include "', "`include `M", "`define ", "<", ">", '"', "\n", "\\\n", " ", "a"]
    pieces += ["/*", "*/", "//"]
    texts = ["".join(rng.choices(pieces, k=rng.randrange(40))).encode() for _ in range(5000)]
    found = [bundle.scan_includes(text) for text in texts]

    # Each system include matched against the regex, as before.
    monkeypatch.setattr(bundle, "_SYSTEM_INCLUDE", re.compile("(?!)"))

    assert [bundle.scan_includes(text) for text in texts] == found


def test_a_line_of_system_includes_never_closed_is_read_in_linear_time():
    started = time.monotonic()

    assert bundle.scan_includes(b"`include <" * 20_000) == []
    # The regex took a minute: from each `<`, it searched the rest of the line for a `>`.
    assert time.monotonic() - started < 5


